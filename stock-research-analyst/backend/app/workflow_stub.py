"""PLACEHOLDER research workflow for Module 1.

Module 1 only needs research tasks to exist, belong to a user, and move through
Pending -> Processing -> Completed/Failed so the history UI can be built and tested.
The real multi-agent analysis plugs in here in later modules: replace the body of
`run_research_workflow` and keep the status updates.
"""
import time
from datetime import datetime, timezone

from . import database
from .config import settings
from .models import ResearchTask
from .stock_catalog import provider_symbol

PERIOD_LABELS = {"1M": "1 Month", "3M": "3 Months", "6M": "6 Months", "1Y": "1 Year", "5Y": "5 Years"}


def run_research_workflow(task_id: int) -> None:
    db = database.SessionLocal()
    try:
        task = db.get(ResearchTask, task_id)
        if task is None:
            return
        task.status = "Processing"
        task.started_at = datetime.now(timezone.utc)
        db.commit()

        try:
            time.sleep(settings.RESEARCH_STUB_DELAY_SECONDS)
            task.report = (
                f"# {task.company_name} ({task.ticker})\n\n"
                f"Market: {task.market}\n"
                f"Data-provider symbol: {provider_symbol(task.ticker, task.market)}\n"
                f"Analysis period: {PERIOD_LABELS.get(task.analysis_period, task.analysis_period)}\n\n"
                "This is a placeholder report generated by the Module 1 stub workflow. "
                "The multi-agent research analysis is added in later modules."
            )
            task.status = "Completed"
            task.completed_at = datetime.now(timezone.utc)
        except Exception as exc:  # record failures clearly
            task.status = "Failed"
            task.error_message = str(exc)[:500]
            task.completed_at = datetime.now(timezone.utc)
        db.commit()
    finally:
        db.close()
